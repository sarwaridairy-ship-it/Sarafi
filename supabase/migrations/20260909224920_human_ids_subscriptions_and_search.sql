      'organizations', (select count(*) from public.organizations),
      'active_subscriptions', (select count(*) from public.organization_subscriptions where status in ('trial', 'active')),
      'pending_payments', (select count(*) from public.subscription_payment_requests where status in ('submitted', 'under_review')),
      'suspended_users', (select count(*) from public.platform_user_access where status = 'suspended')
    )
  ) into result;
  return result;
end;
$$;

create or replace function public.search_counterparties_v7(target_org uuid, search_text text default null)
returns table (
  id uuid,
  customer_number bigint,
  customer_reference text,
  branch_id uuid,
  display_name text,
  counterparty_type text,
  risk_status text,
  phone text,
  notes text
)
language sql
security definer
stable
set search_path = ''
as $$
  select cp.id, cp.customer_number, 'C-' || lpad(cp.customer_number::text, 8, '0'),
    cp.branch_id, cp.display_name, cp.counterparty_type, cp.risk_status, cp.phone, cp.notes
  from public.counterparties cp
  where cp.organization_id = target_org
    and cp.risk_status <> 'blocked'
    and (
      public.can_access_branch_v6(target_org, cp.branch_id, 'customers.manage')
      or public.can_access_branch_v6(target_org, cp.branch_id, 'transactions.view')
      or public.can_access_branch_v6(target_org, cp.branch_id, 'compliance.review')
    )
    and (
      nullif(trim(search_text), '') is null
      or cp.display_name ilike '%' || trim(search_text) || '%'
      or coalesce(cp.phone, '') ilike '%' || trim(search_text) || '%'
      or cp.customer_number::text = regexp_replace(trim(search_text), '[^0-9]', '', 'g')
      or ('C-' || lpad(cp.customer_number::text, 8, '0')) ilike '%' || trim(search_text) || '%'
    )
  order by cp.display_name, cp.id;
$$;

create or replace function public.search_transaction_history_v7(
  target_org uuid,
  search_text text default null,
  target_from date default null,
  target_to date default null,
  page_size integer default 100
)
returns jsonb
language sql
security definer
stable
set search_path = ''
as $$
  with unique_entries as materialized (
    select distinct on (sl.journal_entry_id)
      sl.journal_entry_id, sl.branch_id, sl.entry_status, sl.occurred_at,
      sl.created_by, sl.financial_event_id, sl.immutable_reference,
      sl.event_type, sl.event_metadata
    from public.get_scoped_report_ledger_lines_v6(target_org, target_from, target_to, null, null, 'transactions.view') sl
    order by sl.journal_entry_id, sl.account_id
  ), result_rows as (
    select ue.occurred_at, ue.journal_entry_id, jsonb_build_object(
      'id', ue.journal_entry_id,
      'transaction_number', je.transaction_number,
      'transaction_reference', 'T-' || lpad(je.transaction_number::text, 8, '0'),
      'status', ue.entry_status, 'memo', je.memo, 'occurred_at', ue.occurred_at,
      'branch_id', ue.branch_id, 'event_type', ue.event_type,
      'immutable_reference', ue.immutable_reference,
      'receipt_number', r.receipt_number,
      'source_account_name', ue.event_metadata->>'source_account_name',
      'destination_account_name', ue.event_metadata->>'destination_account_name',
      'source_account_kind', ue.event_metadata->>'source_account_kind',
      'destination_account_kind', ue.event_metadata->>'destination_account_kind',
      'cashbox_name', cb.name, 'counterparty_name', cp.display_name,
      'customer_number', cp.customer_number,
      'customer_reference', case when cp.customer_number is null then null else 'C-' || lpad(cp.customer_number::text, 8, '0') end,
      'employee_name', coalesce(nullif(trim(pr.display_name), ''), 'Team member'),
      'given_amount', ue.event_metadata->>'sold_amount', 'given_currency', ue.event_metadata->>'sold_currency',
      'received_amount', ue.event_metadata->>'bought_amount', 'received_currency', ue.event_metadata->>'bought_currency',
      'currency_code', coalesce(ue.event_metadata->>'currency', ue.event_metadata->>'sold_currency'),
      'amount', coalesce(ue.event_metadata->>'amount', ue.event_metadata->>'sold_amount'),
      'customer_rate', ue.event_metadata->>'customer_rate',
      'fee_amount', ue.event_metadata->>'fee_amount', 'fee_currency', ue.event_metadata->>'fee_currency'
    ) row_data
    from unique_entries ue
    join public.journal_entries je on je.id = ue.journal_entry_id
    left join public.cashboxes cb on cb.id = case
      when ue.event_metadata->>'cashbox_id' ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
        then (ue.event_metadata->>'cashbox_id')::uuid else null end
    left join public.financial_events fe on fe.id = ue.financial_event_id
    left join public.counterparties cp on cp.id = coalesce(fe.counterparty_id, case
      when ue.event_metadata->>'counterparty_id' ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
        then (ue.event_metadata->>'counterparty_id')::uuid else null end) and cp.organization_id = target_org
    left join public.profiles pr on pr.id = ue.created_by
    left join public.receipts r on r.journal_entry_id = ue.journal_entry_id and r.organization_id = target_org
    where nullif(trim(search_text), '') is null
      or je.transaction_number::text = regexp_replace(trim(search_text), '[^0-9]', '', 'g')
      or ('T-' || lpad(je.transaction_number::text, 8, '0')) ilike '%' || trim(search_text) || '%'
      or coalesce(r.receipt_number, '') ilike '%' || trim(search_text) || '%'
      or coalesce(ue.immutable_reference, '') ilike '%' || trim(search_text) || '%'
      or coalesce(cp.display_name, '') ilike '%' || trim(search_text) || '%'
      or coalesce(cp.phone, '') ilike '%' || trim(search_text) || '%'
      or cp.customer_number::text = regexp_replace(trim(search_text), '[^0-9]', '', 'g')
    order by ue.occurred_at desc, ue.journal_entry_id desc
    limit least(greatest(page_size, 1), 1000)
  )
  select coalesce(jsonb_agg(result_rows.row_data order by result_rows.occurred_at desc, result_rows.journal_entry_id desc), '[]'::jsonb)
  from result_rows;
$$;

create or replace function public.get_transaction_detail(target_org uuid, target_entry uuid)
returns jsonb
language plpgsql
security definer
stable
set search_path = ''
as $$
declare result jsonb;
declare branch_id_value uuid;
declare cashbox_id_value uuid;
begin
  select je.branch_id, case
    when fe.metadata->>'cashbox_id' ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
      then (fe.metadata->>'cashbox_id')::uuid else null end
  into branch_id_value, cashbox_id_value
  from public.journal_entries je join public.financial_events fe on fe.id = je.financial_event_id
  where je.id = target_entry and je.organization_id = target_org;
  if not found then return null; end if;
  perform public.require_capability(target_org, 'transactions.view', jsonb_strip_nulls(jsonb_build_object(
    'branch_id', branch_id_value, 'cashbox_id', cashbox_id_value
  )));
  select jsonb_build_object(
    'id', je.id, 'transaction_number', je.transaction_number,
    'transaction_reference', 'T-' || lpad(je.transaction_number::text, 8, '0'),
    'status', je.status, 'memo', je.memo, 'occurred_at', je.occurred_at,
    'branch_id', je.branch_id, 'event_type', fe.event_type,
    'immutable_reference', fe.immutable_reference, 'receipt_number', r.receipt_number,
    'source_account_name', fe.metadata->>'source_account_name',
    'destination_account_name', fe.metadata->>'destination_account_name',
    'source_account_kind', fe.metadata->>'source_account_kind',
    'destination_account_kind', fe.metadata->>'destination_account_kind',
    'cashbox_name', cb.name, 'counterparty_name', cp.display_name,
    'customer_number', cp.customer_number,
    'customer_reference', case when cp.customer_number is null then null else 'C-' || lpad(cp.customer_number::text, 8, '0') end,
    'employee_name', coalesce(nullif(trim(pr.display_name), ''), 'Team member'),
    'given_amount', fe.metadata->>'sold_amount', 'given_currency', fe.metadata->>'sold_currency',
    'received_amount', fe.metadata->>'bought_amount', 'received_currency', fe.metadata->>'bought_currency',
    'currency_code', coalesce(fe.metadata->>'currency', fe.metadata->>'sold_currency'),
    'amount', coalesce(fe.metadata->>'amount', fe.metadata->>'sold_amount'),
    'customer_rate', fe.metadata->>'customer_rate',
    'fee_amount', fe.metadata->>'fee_amount', 'fee_currency', fe.metadata->>'fee_currency'
  ) into result
  from public.journal_entries je
  join public.financial_events fe on fe.id = je.financial_event_id
  left join public.cashboxes cb on cb.id = cashbox_id_value and cb.organization_id = target_org
  left join public.counterparties cp on cp.id = fe.counterparty_id and cp.organization_id = target_org
  left join public.profiles pr on pr.id = je.created_by
  left join public.receipts r on r.journal_entry_id = je.id and r.organization_id = target_org
  where je.id = target_entry and je.organization_id = target_org;
  return result;
end;
$$;

