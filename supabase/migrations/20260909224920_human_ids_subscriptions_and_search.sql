-- Human-facing identifiers, fixed-term subscription pricing, and searchable
-- transaction history. UUIDs remain the internal keys; these numbers are the
-- stable references shown to people and printed on receipts.

alter table public.profiles
  add column user_number bigint generated by default as identity;
alter table public.organizations
  add column business_number bigint generated by default as identity;
alter table public.counterparties
  add column customer_number bigint generated by default as identity;
alter table public.journal_entries
  add column transaction_number bigint generated by default as identity;

create unique index profiles_user_number_key on public.profiles (user_number);
create unique index organizations_business_number_key on public.organizations (business_number);
create unique index counterparties_customer_number_key on public.counterparties (customer_number);
create unique index journal_entries_transaction_number_key on public.journal_entries (transaction_number);
create index counterparties_org_customer_number_idx on public.counterparties (organization_id, customer_number);
create index journal_entries_org_transaction_number_idx on public.journal_entries (organization_id, transaction_number desc);

create table public.subscription_plan_prices (
  id bigint generated always as identity primary key,
  plan_id uuid not null references public.subscription_plans(id) on delete cascade,
  term_months smallint not null check (term_months in (1, 3, 6, 12)),
  price_afn numeric(18,2) not null check (price_afn > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (plan_id, term_months)
);

create index subscription_plan_prices_active_idx
  on public.subscription_plan_prices (plan_id, term_months)
  where active;

alter table public.subscription_plan_prices enable row level security;
create policy published_subscription_price_read
  on public.subscription_plan_prices
  for select to authenticated
  using (
    exists (
      select 1 from public.subscription_plans p
      where p.id = plan_id and (p.status = 'published' or (select public.is_platform_admin()))
    )
  );

revoke all on table public.subscription_plan_prices from public, anon, authenticated;
grant select on table public.subscription_plan_prices to authenticated;

insert into public.subscription_plan_prices (plan_id, term_months, price_afn)
select p.id, prices.term_months, prices.price_afn
from public.subscription_plans p
cross join lateral (
  values
    (1::smallint, p.price_afn),
    (3::smallint, round(p.price_afn * 2.85, 2)),
    (6::smallint, round(p.price_afn * 5.40, 2)),
    (12::smallint, round(p.price_afn * 10.00, 2))
) prices(term_months, price_afn)
where p.status in ('published', 'draft')
on conflict (plan_id, term_months) do update
set price_afn = excluded.price_afn, active = true, updated_at = now();

alter table public.subscription_payment_requests
  add column term_months smallint not null default 1
    check (term_months in (1, 3, 6, 12));

create or replace function public.get_billing_portal(target_org uuid)
returns jsonb
language plpgsql
security definer
stable
set search_path = ''
as $$
declare result jsonb;
begin
  if not exists (
    select 1 from public.organization_memberships
    where organization_id = target_org and user_id = (select auth.uid()) and active and role_code = 'owner'
  ) then raise exception 'Only the business owner can manage the plan'; end if;
  select jsonb_build_object(
    'subscription', (
      select jsonb_build_object(
        'id', s.id, 'status', s.status, 'trial_ends_at', s.trial_ends_at,
        'current_period_end', s.current_period_end, 'plan_id', p.id,
        'plan_code', p.code, 'plan_name_en', p.name_en,
        'plan_name_dari', p.name_dari, 'plan_name_pashto', p.name_pashto
      ) from public.organization_subscriptions s
        join public.subscription_plans p on p.id = s.plan_id
      where s.organization_id = target_org
    ),
    'plans', coalesce((
      select jsonb_agg(
        to_jsonb(p) || jsonb_build_object('term_prices', coalesce((
          select jsonb_agg(jsonb_build_object('term_months', pp.term_months, 'price_afn', pp.price_afn) order by pp.term_months)
          from public.subscription_plan_prices pp where pp.plan_id = p.id and pp.active
        ), '[]'::jsonb))
        order by p.sort_order, p.id
      ) from public.subscription_plans p where p.status = 'published'
    ), '[]'::jsonb),
    'providers', coalesce((select jsonb_agg(to_jsonb(pc) order by pc.code) from public.payment_provider_configs pc where pc.state = 'live'), '[]'::jsonb),
    'requests', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', r.id, 'plan_id', r.plan_id, 'provider_code', r.provider_code,
        'amount_afn', r.amount_afn, 'term_months', r.term_months,
        'payer_reference', r.payer_reference, 'status', r.status,
        'requested_at', r.requested_at, 'review_note', r.review_note
      ) order by r.requested_at desc)
      from public.subscription_payment_requests r where r.organization_id = target_org
    ), '[]'::jsonb)
  ) into result;
  return result;
end;
$$;

drop function if exists public.create_subscription_payment_request(uuid, uuid, text, text, text);
create function public.create_subscription_payment_request(
  target_org uuid,
  target_plan uuid,
  target_provider text,
  term_months_input smallint,
  payer_reference_input text,
  payer_note_input text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare plan_row public.subscription_plans;
declare provider_row public.payment_provider_configs;
declare subscription_row public.organization_subscriptions;
declare request_row public.subscription_payment_requests;
declare selected_price numeric(18,2);
begin
  if not exists (
    select 1 from public.organization_memberships
    where organization_id = target_org and user_id = (select auth.uid()) and active and role_code = 'owner'
  ) then raise exception 'Only the business owner can request plan activation'; end if;
  if term_months_input not in (1, 3, 6, 12) then raise exception 'Choose a valid subscription term'; end if;
  select * into plan_row from public.subscription_plans where id = target_plan and status = 'published';
  select pp.price_afn into selected_price from public.subscription_plan_prices pp
    where pp.plan_id = target_plan and pp.term_months = term_months_input and pp.active;
  if plan_row.id is null or selected_price is null then raise exception 'This plan and term are not available for payment'; end if;
  select * into provider_row from public.payment_provider_configs where code = target_provider and state = 'live';
  if provider_row.code is null then raise exception 'This payment method is not active'; end if;
  if provider_row.provider_mode = 'manual_review' and length(trim(coalesce(payer_reference_input, ''))) < 3 then
    raise exception 'Receipt reference is required';
  end if;
  select * into subscription_row from public.organization_subscriptions where organization_id = target_org for update;
  if subscription_row.id is null then raise exception 'Subscription was not found'; end if;
  insert into public.subscription_payment_requests (
    organization_id, subscription_id, plan_id, provider_code, amount_afn, term_months,
    payer_reference, payer_note, status, requested_by
  ) values (
    target_org, subscription_row.id, plan_row.id, provider_row.code, selected_price, term_months_input,
    nullif(trim(payer_reference_input), ''), nullif(trim(payer_note_input), ''),
    case when provider_row.provider_mode = 'manual_review' then 'submitted' else 'awaiting_payment' end,
    (select auth.uid())
  ) returning * into request_row;
  update public.organization_subscriptions set status = 'pending_payment', updated_at = now()
    where id = subscription_row.id and status not in ('active', 'suspended');
  return jsonb_build_object('request', to_jsonb(request_row), 'checkout_url', provider_row.public_checkout_url);
end;
$$;

create or replace function public.decide_subscription_payment(
  target_request uuid,
  decision text,
  review_note_input text
)
returns public.subscription_payment_requests
language plpgsql
security definer
set search_path = ''
as $$
declare request_row public.subscription_payment_requests;
declare next_end timestamptz;
begin
  perform public.require_platform_admin(true);
  if decision not in ('approved', 'rejected') then raise exception 'Choose approve or reject'; end if;
  if length(trim(coalesce(review_note_input, ''))) < 3 then raise exception 'Administrator note is required'; end if;
  select * into request_row from public.subscription_payment_requests where id = target_request for update;
  if request_row.id is null or request_row.status not in ('submitted', 'under_review') then
    raise exception 'Payment request is no longer available';
  end if;
  select greatest(coalesce(s.current_period_end, now()), now()) + make_interval(months => request_row.term_months)
    into next_end from public.organization_subscriptions s where s.id = request_row.subscription_id for update;
  update public.subscription_payment_requests set
    status = decision, reviewed_by = (select auth.uid()), reviewed_at = now(), review_note = trim(review_note_input)
    where id = target_request returning * into request_row;
  if decision = 'approved' then
    update public.organization_subscriptions set
      plan_id = request_row.plan_id, status = 'active', current_period_start = now(),
      current_period_end = next_end, activated_by = (select auth.uid()),
      suspension_reason = null, updated_at = now()
      where id = request_row.subscription_id;
  end if;
  insert into public.platform_audit_events (actor_user_id, event_type, target_organization_id, metadata)
    values ((select auth.uid()), 'subscription_payment_' || decision, request_row.organization_id,
      jsonb_build_object('request_id', request_row.id, 'amount_afn', request_row.amount_afn,
        'term_months', request_row.term_months, 'note', trim(review_note_input)));
  return request_row;
end;
$$;

create or replace function public.get_platform_organization_users(target_org uuid)
returns jsonb
language plpgsql
security definer
volatile
set search_path = ''
as $$
declare result jsonb;
begin
  perform public.require_platform_admin(false);
  select coalesce(jsonb_agg(jsonb_build_object(
    'user_id', m.user_id,
    'user_number', p.user_number,
    'user_reference', 'U-' || lpad(p.user_number::text, 8, '0'),
    'membership_id', m.id,
    'display_name', coalesce(nullif(trim(p.display_name), ''), split_part(u.email, '@', 1), 'User'),
    'email', u.email, 'role_code', m.role_code, 'membership_active', m.active,
    'platform_status', coalesce(a.status, 'active'), 'platform_reason', a.reason,
    'joined_at', m.created_at
  ) order by m.created_at), '[]'::jsonb) into result
  from public.organization_memberships m
  join auth.users u on u.id = m.user_id
  left join public.profiles p on p.id = m.user_id
  left join public.platform_user_access a on a.user_id = m.user_id
  where m.organization_id = target_org;
  return result;
end;
$$;

create or replace function public.get_platform_admin_console()
returns jsonb
language plpgsql
security definer
volatile
set search_path = ''
as $$
declare result jsonb;
begin
  perform public.require_platform_admin(false);
  select jsonb_build_object(
    'organizations', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', o.id, 'business_number', o.business_number,
