export function translate(language: Language, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}
export function isRtl(language: Language): boolean {
  return language !== "en";
}
export function requiredTranslationKeys(): TranslationKey[] {
  return Object.keys(translations.en) as TranslationKey[];
}
export function hasCompleteTranslations(language: Language): boolean {
  return requiredTranslationKeys().every((key) =>
    Boolean(translations[language][key]),
  );
}
